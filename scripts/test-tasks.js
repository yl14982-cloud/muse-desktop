'use strict';
const assert=require('node:assert/strict');
const t=require('../task-store');
const s=t.createStore();
assert.equal(s.notionEnabled,false);assert.equal(s.moodSource,'manual');assert.deepEqual(t.todayTasks(s),[]);
assert.throws(()=>t.addLocal(s,'   '));assert.throws(()=>t.addLocal(s,'x'.repeat(121)));
const a=t.addLocal(s,'  Review DSP  '),b=t.addLocal(s,'Write a summary'),c=t.addLocal(s,'Take a walk');
assert.equal(a.title,'Review DSP');assert.equal(new Set(s.localTasks.map(t=>t.id)).size,3);
t.selectTasks(s,[a.id,b.id]);assert.equal(t.todayTasks(s).length,2);
assert.throws(()=>t.selectTasks(s,[a.id,b.id,c.id]));assert.throws(()=>t.selectTasks(s,['missing']));
t.toggleLocal(s,a.id);assert.equal(t.todayTasks(s)[0].done,true);
t.toggleLocal(s,a.id);assert.equal(t.todayTasks(s)[0].done,false);
t.setMood(s,'Focused');assert.equal(s.moodSource,'manual');assert.throws(()=>t.setMood(s,'Unknown'));
t.enableNotion(s,true);t.replaceNotion(s,[{id:'remote-1',title:'Remote task',status:'Ready'}]);
t.selectTasks(s,[a.id,'remote-1']);t.replaceNotion(s,[{id:'remote-1',title:'Updated title',status:'Ready'}]);
assert.equal(t.todayTasks(s)[1].title,'Updated title');assert.equal(s.localTasks.length,3);
assert.throws(()=>t.toggleLocal(s,'remote-1'));
t.replaceNotion(s,[]);assert.deepEqual(s.selectedIds,[a.id]);assert.equal(t.todayTasks(s)[0].title,'Review DSP');
t.replaceNotion(s,[{id:'remote-2',title:'Another remote',status:'Ready'}]);t.selectTasks(s,[a.id,'remote-2']);
t.enableNotion(s,false);assert.deepEqual(s.selectedIds,[a.id]);assert.equal(t.allTasks(s).length,3);
const restored=t.createStore(JSON.parse(JSON.stringify(s)));assert.deepEqual(restored,s);
const migrated=t.createStore(null,{mood:'Stressed',source:'Notion Muse State',tasks:[{id:'old-1',title:'Existing task'}]},true,['old-1']);
assert.equal(migrated.notionEnabled,true);assert.equal(migrated.moodSource,'notion');assert.equal(t.todayTasks(migrated)[0].title,'Existing task');
const oldDemo=t.createStore(null,{mood:'Calm',source:'demo',tasks:[{id:'demo',title:'Fake sample'}]},false,['demo']);assert.deepEqual(t.allTasks(oldDemo),[]);
console.log('PASS: local task validation, selection limit, completion/reopen, mood, remote merge, disconnect, persistence and legacy migration');
